/**
 * Physical traversal category of a connection between facilities.
 */
public enum TraversalType {
    /** A ramp connection. */
    RAMP,
    /** A ramp recorded as sheltered. */
    SHELTERED_RAMP,
    /** A lift connection. */
    LIFT,
    /** A pedestrian path. */
    PATH,
    /** Another recorded traversal category. */
    OTHER
}
